            <p>Observation never begins from outside a moment. The observer is already situated within its locality, relations and conditions.</p>
            <p>Educating perception is not confined to formal learning environments. It can occur wherever there is sufficient time, safety and openness for attention to steady, observation to deepen, and experience to reveal relationships that may previously have remained unnoticed.</p>
            <p>To curate observation is not to curate its conclusion.</p>
            <p>The conditions of encounter may be shaped—what receives attention, how much time is allowed, which questions remain open and whether an experience is revisited—without predetermining what another person must perceive.</p>
            <p>Neither the world nor the observer stands outside the relation.</p>
