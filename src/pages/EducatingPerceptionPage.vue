            <h3 class="ep-subhead">At a supermarket checkout</h3>
            <p>During an ordinary visit to a supermarket, allow your attention to remain more fully with the cashier than it typically might. Notice what can be directly observed—their tone, pace, pauses, gestures and way of responding.</p>
            <p>Notice also the conditions surrounding the encounter: the queue, the sounds, the pace of the transaction, other customers and the demands upon the cashier’s attention. What interpretation is shaping how you are meeting the moment?</p>
            <p>Then include your own participation within the observation. How might your attention, tone, expectations or the way you respond already be affecting the encounter? What might become possible if one of them changed?</p>
            <p>If the encounter is recorded or shared, remain with your own attention, interpretation and participation—not an evaluation of the other person.</p>
            <p class="ep-sequence">Encounter · Observe · Record · Share · Return</p>
