            <p class="ep-eyebrow">The dignity of the ordinary moment</p>
            <h2>Much of life occurs in moments that do not announce their significance.</h2>
            <p>Because they are ordinary, attention readily passes over them—drawn toward what has already happened, what may happen next, or what appears more consequential.</p>
            <p>The significance of the present moment lies precisely here: it is where life is actually being lived, where participation is already occurring, and where another response becomes possible.</p>
            <p>Even when such moments pass largely unattended, our presence continues to shape the conditions of a locality. Their apparent insignificance makes the cultivation of attention especially important. As they become more perceptible, we become more able to respond consciously and intentionally to what is occurring.</p>
            <p>Here, care becomes behavioural—perceptible in how we attend, choose and respond, and in the conditions our presence creates for others.</p>
            <p>These are the moments through which a locality continually becomes itself. Their significance lies not in how consequential they appear, but in the conditions they quietly help create. What becomes embodied here enters what others encounter—and may, through their participation, be regenerated elsewhere.</p>
            <blockquote class="ep-quote">
