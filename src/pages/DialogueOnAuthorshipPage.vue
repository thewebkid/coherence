          <p>None of these are "wrong." But each one introduces a slight exteriority—a step outside the continuity.</p>

          <p>And the aperture narrows.</p>

          <p>What keeps it available is not effort. Not vigilance in the tense sense. More like a soft non-interference with what is already occurring.</p>

          <p class="speaker speaker-section">Sovereign II —</p>

          <p>Are there examples you can cite?</p>

          <p class="speaker speaker-section">Sovereign I —</p>

